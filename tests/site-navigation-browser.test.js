import assert from 'node:assert/strict';
import test from 'node:test';
import { realBrowser, browserOptions } from './helpers/real-browser.js';

test('Music and Software are direct links and GitHub is available on desktop and mobile', browserOptions, async (t) => {
  const { base, context, page } = await realBrowser(t);
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  await page.goto(`${base}/blog`);
  const desktop = page.getByRole('navigation', { name: 'Main navigation', exact: true });
  assert.equal(await desktop.getByRole('link', { name: 'Visit my GitHub profile', exact: true }).getAttribute('href'), 'https://github.com/GVPproj');
  const music = desktop.getByRole('link', { name: 'Music', exact: true });
  assert.equal(await music.getAttribute('href'), '/music');
  assert.equal(await music.locator('svg').count(), 0);
  assert.equal(await desktop.getByRole('button', { name: 'Music', exact: true }).count(), 0);
  assert.equal(await page.locator('#music-menu').count(), 0);
  await music.focus();
  await page.keyboard.press('Enter');
  await page.getByRole('heading', { name: 'Music', exact: true }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/music');
  assert.equal(await music.getAttribute('aria-current'), 'page');

  const software = desktop.getByRole('link', { name: 'Software', exact: true });
  assert.equal(await software.locator('svg').count(), 0);
  assert.equal(await page.locator('#software-menu').count(), 0);
  await software.click();
  await page.getByRole('heading', { name: 'Software', exact: true }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/software');
  assert.equal(await software.getAttribute('aria-current'), 'page');
  assert.equal(await music.getAttribute('aria-current'), null);

  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open menu', exact: true }).click();
  const mobile = page.getByRole('navigation', { name: 'Mobile navigation', exact: true });
  assert.equal(await mobile.getByRole('link', { name: 'GitHub', exact: true }).getAttribute('href'), 'https://github.com/GVPproj');
  const mobileSoftware = mobile.getByRole('link', { name: 'Software', exact: true });
  assert.equal(await mobileSoftware.getAttribute('href'), '/software');
  assert.equal(await mobileSoftware.getAttribute('aria-current'), 'page');
  assert.equal(await mobileSoftware.locator('svg, .chev').count(), 0);
  assert.equal(await mobile.locator('summary').filter({ hasText: 'Software' }).count(), 0);
  const mobileMusic = mobile.getByRole('link', { name: 'Music', exact: true });
  assert.equal(await mobileMusic.getAttribute('href'), '/music');
  assert.equal(await mobile.locator('summary').filter({ hasText: 'Music' }).count(), 0);
  await mobileMusic.click();
  await page.getByRole('heading', { name: 'Music', exact: true }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/music');
  assert.equal(await page.locator('#site-nav').evaluate(el => el.matches(':popover-open')), false);
  await page.getByRole('button', { name: 'Open menu', exact: true }).click();
  assert.equal(await mobileMusic.getAttribute('aria-current'), 'page');
  assert.equal(await mobileSoftware.getAttribute('aria-current'), null);
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => document.documentElement.style.overflow === '');
});
